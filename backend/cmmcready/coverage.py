"""What the collectors automate: a coverage report generated from ``rules.yml``.

``python -m cmmcready catalog --coverage-md`` prints it, ``--write`` updates the
committed copies and ``--check`` (run in CI) fails when they are out of date:

- ``docs/COLLECTOR_COVERAGE.md``: every rule, with the objective it informs and
  what the collector is allowed to record;
- the README section between the ``coverage:start`` / ``coverage:end`` markers:
  a per-family summary of automated and assessor-only objectives.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from . import config
from .catalog import load_catalog
from .evidence import m365, windows
from .evidence.engine import Rule, load_rules

COVERAGE_DOC = config.REPO_DIR / "docs" / "COLLECTOR_COVERAGE.md"
README = config.REPO_DIR / "README.md"
START = "<!-- coverage:start (generated by `python -m cmmcready catalog --coverage-md --write`) -->"
END = "<!-- coverage:end -->"

COLLECTORS = ((windows.COLLECTOR, "Windows", "collectors/collect-windows.ps1"),
              (m365.COLLECTOR, "Microsoft 365 / Entra ID", "collectors/collect-m365.ps1"))

# What a rule may record for its objectives (see engine.py for the rule semantics).
DECIDES = "Met or Not met"
MET_ONLY = "Met only"
NOT_MET_ONLY = "Not met only"
SUPPORTING = "Supporting evidence"
INFO = "Information for the assessor"


@dataclass(frozen=True)
class Row:
    collector: str
    check_id: str
    rule_id: str
    objective_id: str
    outcome: str


def outcome(rule: Rule) -> str:
    if rule.info is not None:
        return INFO
    can_fail = rule.unmet_if is not None or rule.fail_result == "not_met"
    can_pass = rule.met_result == "met"
    if can_pass and can_fail:
        return DECIDES
    if can_pass:
        return MET_ONLY
    if can_fail:
        return NOT_MET_ONLY
    return SUPPORTING


def rows() -> list[Row]:
    out = []
    for collector, _label, _script in COLLECTORS:
        for check_id, rules in load_rules(collector).items():
            for rule in rules:
                out += [Row(collector, check_id, rule.id, oid, outcome(rule)) for oid in rule.objectives]
    return out


def _cell(text: str) -> str:
    return text.replace("|", r"\|")


def _id_key(oid: str) -> tuple:
    req, letter = oid.rstrip("]").split("[")
    return tuple(int(p) for p in req.split(".")) + (letter,)


def summary() -> dict:
    catalog = load_catalog()
    all_rows = rows()
    covered = {r.objective_id for r in all_rows}
    can_meet = {r.objective_id for r in all_rows if r.outcome in (DECIDES, MET_ONLY)}
    families = []
    for fam in catalog.families():
        oids = [o.id for r in catalog.requirements if r.family == fam.code for o in r.objectives]
        families.append({
            "family": f"{fam.number} {fam.name}",
            "objectives": len(oids),
            "covered": sum(1 for o in oids if o in covered),
            "can_meet": sum(1 for o in oids if o in can_meet),
        })
    return {
        "objectives": catalog.objective_count,
        "requirements": len(catalog.requirements),
        "covered": len(covered),
        "covered_reqs": len({o.split("[")[0] for o in covered}),
        "can_meet": len(can_meet),
        "rules": len({(r.collector, r.check_id, r.rule_id) for r in all_rows}),
        "families": families,
    }


def readme_section() -> str:
    s = summary()
    manual = s["objectives"] - s["covered"]
    lines = [
        f"The collectors run {s['rules']} rules that inform **{s['covered']} of the {s['objectives']} "
        f"assessment objectives** (in {s['covered_reqs']} of the {s['requirements']} requirements). "
        f"A collector can mark only {s['can_meet']} of those objectives Met. For the rest, a compliant "
        "setting is recorded as supporting evidence, because one host or tenant setting does not show "
        "that an organization-wide objective is met. "
        f"The other {manual} objectives (policies, training, physical protection, personnel screening, "
        "incident response and so on) are answered by the assessor alone.",
        "",
        "| Family | Objectives | With collector evidence | Collector can mark Met | Assessor only |",
        "|---|---:|---:|---:|---:|",
    ]
    for f in s["families"]:
        lines.append(f"| {f['family']} | {f['objectives']} | {f['covered']} | {f['can_meet']} | "
                     f"{f['objectives'] - f['covered']} |")
    lines.append(f"| **Total** | **{s['objectives']}** | **{s['covered']}** | **{s['can_meet']}** | "
                 f"**{manual}** |")
    lines += ["", "Every rule, with the objective it informs and what it may record, is listed in "
              "[docs/COLLECTOR_COVERAGE.md](docs/COLLECTOR_COVERAGE.md)."]
    return "\n".join(lines) + "\n"


def coverage_markdown() -> str:
    catalog = load_catalog()
    texts = {o.id: o.text for r in catalog.requirements for o in r.objectives}
    all_rows = rows()
    lines = [
        "# Collector coverage",
        "",
        "Generated from `backend/cmmcready/evidence/rules.yml` by "
        "`python -m cmmcready catalog --coverage-md --write`. CI fails if this file is out of date.",
        "",
        "Each row is one rule applied to one NIST SP 800-171A assessment objective. "
        "The last column says what the rule is allowed to record:",
        "",
        f"- **{DECIDES}**: the setting decides the objective for that host or tenant.",
        f"- **{MET_ONLY}**: a compliant value meets the objective; anything else leaves it Not assessed, "
        "because the control may be implemented another way.",
        f"- **{NOT_MET_ONLY}**: a clear gap fails the objective, but a compliant value is only supporting "
        "evidence (Not assessed), because one setting does not show the whole objective is met.",
        f"- **{SUPPORTING}**: always recorded as Not assessed, with the observed value shown to the assessor.",
        f"- **{INFO}**: the observed values are listed for the assessor to review (for example group members).",
        "",
        "A check the collector could not read (no administrator rights, a missing module, a missing "
        "licence, output in an unexpected language) is always Not assessed, never Met or Not met. "
        "When several rules inform one objective, any Not met wins, and Met needs every rule to be Met. "
        "The assessor's own answer always overrides collector evidence; a disagreement is flagged as a conflict.",
        "",
    ]
    for collector, label, script in COLLECTORS:
        mine = sorted((r for r in all_rows if r.collector == collector),
                      key=lambda r: (_id_key(r.objective_id), r.check_id, r.rule_id))
        lines += [f"## {label} (`{script}`)", "",
                  "| Objective | Determine if | Check | Rule | Collector may record |",
                  "|---|---|---|---|---|"]
        for r in mine:
            lines.append(f"| {r.objective_id} | {_cell(texts[r.objective_id])} | `{r.check_id}` | "
                         f"`{r.rule_id}` | {r.outcome} |")
        lines.append("")
    return "\n".join(lines)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""


def _readme_with(section: str, readme: str) -> str:
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"README.md has no coverage markers ({START} ... {END})")
    return readme[: start + len(START)] + "\n" + section + readme[end:]


def stale_files() -> list[str]:
    """Committed copies that differ from a fresh render (empty when current)."""
    stale = []
    if _read(COVERAGE_DOC) != coverage_markdown():
        stale.append("docs/COLLECTOR_COVERAGE.md")
    readme = _read(README)
    try:
        if _readme_with(readme_section(), readme) != readme:
            stale.append("README.md")
    except ValueError:
        stale.append("README.md (no coverage markers)")
    return stale


def write() -> None:
    updated = _readme_with(readme_section(), _read(README))  # fails before writing anything
    COVERAGE_DOC.parent.mkdir(parents=True, exist_ok=True)
    with open(COVERAGE_DOC, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(coverage_markdown())
    with open(README, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(updated)
